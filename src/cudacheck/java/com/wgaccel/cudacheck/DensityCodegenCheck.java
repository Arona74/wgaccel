package com.wgaccel.cudacheck;

import com.wgaccel.gpu.DensityCodegen;
import com.wgaccel.gpu.FillGpu;
import com.wgaccel.gpu.Gpu;
import java.nio.DoubleBuffer;
import java.nio.IntBuffer;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.List;
import java.util.Locale;
import java.util.Random;
import net.minecraft.world.level.levelgen.XoroshiroRandomSource;
import net.minecraft.world.level.levelgen.synth.NormalNoise;
import org.lwjgl.system.MemoryUtil;

/**
 * Outside the game (`gradlew.bat cudaDensityCheck`): stand-in density function trees of every kind the overworld uses
 * (named like vanilla's records, with real NormalNoises), their CUDA generated by {@link DensityCodegen}, compiled by
 * NVRTC and run on the GPU. Catches codegen and CUDA mistakes; the in-game check compares with vanilla itself.
 */
public final class DensityCodegenCheck {
   private DensityCodegenCheck() {
   }

   private static java.nio.IntBuffer ints(int[] values) {
      return MemoryUtil.memAllocInt(values.length).put(0, values);
   }

   private static DensityFunctions.HolderHolder held(Object function) {
      return new DensityFunctions.HolderHolder(new DensityFunctions.Direct(function));
   }

   public static void main(String[] args) throws Exception {
      NormalNoise jagged = NormalNoise.create(new XoroshiroRandomSource(1L), new NormalNoise.NoiseParameters(-16, 1.0, 1.0, 1.0, 1.0));
      NormalNoise cave = NormalNoise.create(new XoroshiroRandomSource(2L), new NormalNoise.NoiseParameters(-7, 0.4, 0.5, 1.0));
      DensityFunctions.Noise noise = new DensityFunctions.Noise(new DensityFunctions.NoiseHolder(null, jagged), 1500.0, 0.0);
      DensityFunctions.Noise noise3d = new DensityFunctions.Noise(new DensityFunctions.NoiseHolder(null, cave), 0.75, 0.5);
      DensityFunctions.Noise missing = new DensityFunctions.Noise(new DensityFunctions.NoiseHolder(null, null), 1.0, 1.0);
      DensityFunctions.Constant one = new DensityFunctions.Constant(1.0);
      DensityFunctions.Constant half = new DensityFunctions.Constant(0.5);
      CellSampler height = new CellSampler(null, "HEIGHT");
      CellSampler erosion = new CellSampler(null, "EROSION");
      DensityFunctions.YClampedGradient gradient = new DensityFunctions.YClampedGradient(-64, 320, 1.5, -1.5);
      DensityFunctions.Ap2 add = new DensityFunctions.Ap2(DensityFunctions.TwoType.ADD, held(gradient), held(noise3d), -3.0, 3.0);
      DensityFunctions.Ap2 mul = new DensityFunctions.Ap2(DensityFunctions.TwoType.MUL, held(add), held(half), -1.5, 1.5);
      DensityFunctions.Ap2 min = new DensityFunctions.Ap2(DensityFunctions.TwoType.MIN, held(mul), held(noise), -2.0, 1.5);
      DensityFunctions.Ap2 max = new DensityFunctions.Ap2(DensityFunctions.TwoType.MAX, held(min), held(gradient), -1.5, 2.0);
      List<Object> all = new ArrayList<>(List.of(noise, noise3d, missing, height, gradient, add, mul, min, max));
      for (DensityFunctions.MappedType type : DensityFunctions.MappedType.values()) {
         all.add(new DensityFunctions.Mapped(type, held(max), -2.0, 2.0));
      }

      DensityFunctions.Clamp clamp = new DensityFunctions.Clamp(held(add), -1.0, 1.0);
      DensityFunctions.RangeChoice range = new DensityFunctions.RangeChoice(held(noise3d), -1000000.0, 0.1, held(clamp), held(mul));
      DensityFunctions.WeirdScaledSampler weird1 = new DensityFunctions.WeirdScaledSampler(held(noise3d), new DensityFunctions.NoiseHolder(null, cave),
         DensityFunctions.Rarity.TYPE1);
      DensityFunctions.WeirdScaledSampler weird2 = new DensityFunctions.WeirdScaledSampler(held(noise), new DensityFunctions.NoiseHolder(null, jagged),
         DensityFunctions.Rarity.TYPE2);
      CubicSpline.Multipoint inner = new CubicSpline.Multipoint(new DensityFunctions.Spline.Coordinate(new DensityFunctions.Direct(erosion)),
         new float[] {-0.5F, 0.0F, 0.5F}, List.of(new CubicSpline.Constant(-0.2F), new CubicSpline.Constant(0.1F), new CubicSpline.Constant(0.4F)),
         new float[] {0.0F, 0.5F, 0.0F}, -0.2F, 0.4F);
      CubicSpline.Multipoint outer = new CubicSpline.Multipoint(new DensityFunctions.Spline.Coordinate(new DensityFunctions.Direct(height)),
         new float[] {-1.0F, -0.2F, 0.3F, 1.0F}, List.of(new CubicSpline.Constant(-1.0F), inner, new CubicSpline.Constant(0.2F), inner),
         new float[] {0.3F, 0.0F, -0.4F, 0.0F}, -1.0F, 0.4F);
      DensityFunctions.Spline spline = new DensityFunctions.Spline(outer);
      DensityFunctions.Marker interpolated = new DensityFunctions.Marker(DensityFunctions.MarkerType.Interpolated, held(spline));
      DensityFunctions.BlendDensity blend = new DensityFunctions.BlendDensity(held(interpolated));
      ClampToNearestUnit unit = new ClampToNearestUnit(held(blend), 128);
      DensityFunctions.Ap2 top = new DensityFunctions.Ap2(DensityFunctions.TwoType.ADD, held(unit), held(new DensityFunctions.Ap2(DensityFunctions.TwoType.MUL,
         held(DensityFunctions.BlendAlpha.INSTANCE), held(range), -1.0, 1.0)), -3.0, 3.0);
      all.addAll(List.of(clamp, range, weird1, weird2, spline, interpolated, blend, unit, DensityFunctions.BlendAlpha.INSTANCE, top, one));

      DensityCodegen codegen = new DensityCodegen();
      List<Object> roots = new ArrayList<>();
      for (Object node : all) {
         if (!DensityCodegen.kind(node).equals("Constant")) {
            codegen.function(node);
            roots.add(node);
         }
      }

      roots.sort(Comparator.comparingInt(codegen::id));
      List<String> names = new ArrayList<>();
      for (Object root : roots) {
         names.add(codegen.function(root));
      }

      String source = codegen.source(names);
      Path saved = Path.of("build", "density-check.cu");
      Files.writeString(saved, source);
      int points = 4096;
      IntBuffer xs = MemoryUtil.memAllocInt(points);
      IntBuffer ys = MemoryUtil.memAllocInt(points);
      IntBuffer zs = MemoryUtil.memAllocInt(points);
      Random random = new Random(4L);
      for (int p = 0; p < points; p++) {
         xs.put(p, random.nextInt(2_000_000) - 1_000_000);
         ys.put(p, random.nextInt(1152) - 128);
         zs.put(p, random.nextInt(2_000_000) - 1_000_000);
      }

      int samplers = codegen.cellSamplers().size();
      DoubleBuffer cells = MemoryUtil.memAllocDouble(Math.max(1, samplers * points));
      for (int i = 0; i < samplers * points; i++) {
         cells.put(i, random.nextDouble() * 2.0 - 1.0);
      }

      double[] noiseData = codegen.noiseData();
      int[] permutations = codegen.permutations();
      int rows = roots.size();
      long start = System.nanoTime();
      try (Gpu gpu = new Gpu(source, "density_check.cu")) {
         System.out.printf(Locale.ROOT, "%d roots, %d CellSampler inputs, CUDA source %,d bytes (saved as %s); compiled and loaded in %.0f ms%n", rows, samplers,
            source.length(), saved, (System.nanoTime() - start) / 1.0e6);
         long out = gpu.allocate(8L * rows * points);
         gpu.run("densityCheck", (points + 255) / 256, rows, xs, ys, zs, cells, points, MemoryUtil.memAllocDouble(Math.max(1, noiseData.length)).put(0, noiseData),
            MemoryUtil.memAllocInt(Math.max(1, permutations.length)).put(0, permutations), 0, 0, out);
         DoubleBuffer values = MemoryUtil.memAllocDouble(rows * points);
         gpu.download(out, values);
         for (int r = 0; r < rows; r++) {
            double lo = Double.POSITIVE_INFINITY;
            double hi = Double.NEGATIVE_INFINITY;
            int nan = 0;
            for (int p = 0; p < points; p++) {
               double v = values.get(r * points + p);
               if (Double.isNaN(v)) {
                  nan++;
               } else {
                  lo = Math.min(lo, v);
                  hi = Math.max(hi, v);
               }
            }

            System.out.printf(Locale.ROOT, "%-5s %-22s min %-22s max %-22s NaN %d%n", names.get(r), DensityCodegen.kind(roots.get(r)), lo, hi, nan);
         }
      }

      chunk(new DensityFunctions.Ap2(DensityFunctions.TwoType.ADD, held(top),
         held(new DensityFunctions.Marker(DensityFunctions.MarkerType.FlatCache, held(add))), -6.0, 6.0));
   }

   /** One chunk's final density as NoiseChunk fills it (corners, then blocks), on the GPU with made-up CellSampler columns. */
   private static void chunk(Object root) throws Exception {
      DensityCodegen codegen = new DensityCodegen();
      String block = codegen.function(root, DensityCodegen.Mode.BLOCK);
      List<String> corners = new ArrayList<>();
      for (Object input : codegen.interpolatorInputs()) {
         corners.add(codegen.function(input, DensityCodegen.Mode.CORNER));
      }

      String step = codegen.function(root, DensityCodegen.Mode.BLOCK_STEP);
      String source = codegen.chunkSource(block, step, corners) + DensityCodegen.statesKernel(step, step, step, step);
      Files.writeString(Path.of("build", "density-chunk-check.cu"), source);
      int cellCountY = 58;
      int height = cellCountY * 8;
      int per = 5 * 5 * (cellCountY + 1);
      Random random = new Random(5L);
      int samplers = codegen.cellSamplers().size();
      DoubleBuffer cells = MemoryUtil.memAllocDouble(Math.max(1, samplers * 289));
      for (int i = 0; i < samplers * 289; i++) {
         cells.put(i, random.nextDouble() * 2.0 - 1.0);
      }

      double[] noiseData = codegen.noiseData();
      int[] permutations = codegen.permutations();
      long start = System.nanoTime();
      try (Gpu gpu = new Gpu(source, "density_chunk_check.cu")) {
         double compileMs = (System.nanoTime() - start) / 1.0e6;
         long dcells = gpu.upload(cells);
         long dnd = gpu.upload(MemoryUtil.memAllocDouble(Math.max(1, noiseData.length)).put(0, noiseData));
         long dnp = gpu.upload(MemoryUtil.memAllocInt(Math.max(1, permutations.length)).put(0, permutations));
         long dcorners = gpu.allocate(8L * Math.max(1, corners.size() * per));
         long dout = gpu.allocate(8L * 256 * height);
         long run = System.nanoTime();
         gpu.run("densityCorners", (corners.size() * per + 255) / 256, 1, dcells, dnd, dnp, -4096, 8192, -16, cellCountY, 4, 8, corners.size(), dcorners);
         gpu.run("densityBlocks", (256 * height + 255) / 256, 1, dcells, dnd, dnp, -4096, 8192, -16, cellCountY, 4, 8, dcorners, per, dout);
         long dcodes = gpu.allocate(4L * 256 * height);
         int[] lava = new int[256];
         java.util.Arrays.fill(lava, -54);
         int[] grid = {-257, -12, 511, 3, 42, 3};
         int[] loc = new int[3 * 3 * 42 * 3];
         int[] status = new int[3 * 42 * 3 * 2];
         for (int i = 0; i < 3 * 42 * 3; i++) {
            int gx = i % 3;
            int gz = (i / 3) % 3;
            int gy = i / 9;
            loc[i * 3] = (-257 + gx) * 16 + random.nextInt(10);
            loc[i * 3 + 1] = (-12 + gy) * 12 + random.nextInt(9);
            loc[i * 3 + 2] = (511 + gz) * 16 + random.nextInt(10);
            status[i * 2] = random.nextInt(3) == 0 ? 63 : -60;
            status[i * 2 + 1] = random.nextInt(4) == 0 ? 9 : 8;
         }

         gpu.run("densityStates", (256 * height + 255) / 256, 1, dcells, dnd, dnp, -4096, 8192, -16, cellCountY, 4, 8, dcorners, per, dout, 123456789L,
            -987654321L, 1, ints(grid), ints(loc), ints(status), ints(lava), 63, 8, 1, dcodes);
         java.nio.IntBuffer codes = MemoryUtil.memAllocInt(256 * height);
         gpu.download(dcodes, codes);
         int[] counts = new int[11];
         for (int i = 0; i < 256 * height; i++) {
            counts[codes.get(i) + 1]++;
         }

         System.out.println("state codes (-1 to 9): " + java.util.Arrays.toString(counts));
         double runMs = (System.nanoTime() - run) / 1.0e6;
         DoubleBuffer out = MemoryUtil.memAllocDouble(256 * height);
         gpu.download(dout, out);
         double lo = Double.POSITIVE_INFINITY;
         double hi = Double.NEGATIVE_INFINITY;
         int nan = 0;
         for (int i = 0; i < 256 * height; i++) {
            double v = out.get(i);
            if (Double.isNaN(v)) {
               nan++;
            } else {
               lo = Math.min(lo, v);
               hi = Math.max(hi, v);
            }
         }

         System.out.printf(Locale.ROOT, "chunk: %d interpolators, %d CellSampler inputs, compiled in %.0f ms; %,d blocks in %.2f ms: min %s, max %s, NaN %d%n",
            corners.size(), samplers, compileMs, 256 * height, runMs, lo, hi, nan);

         // The noise fill (G2.5): fillStates with vanilla's aquifer must give densityStates' codes on the step density.
         long dstep = gpu.allocate(8L * 256 * height);
         gpu.run("densityBlocksStep", (256 * height + 255) / 256, 1, dcells, dnd, dnp, -4096, 8192, -16, cellCountY, 4, 8, dcorners, per, dstep);
         gpu.run("densityStates", (256 * height + 255) / 256, 1, dcells, dnd, dnp, -4096, 8192, -16, cellCountY, 4, 8, dcorners, per, dstep, 123456789L,
            -987654321L, 1, ints(grid), ints(loc), ints(status), ints(lava), 63, 8, 1, dcodes);
         gpu.download(dcodes, codes);
         long fillStart = System.nanoTime();
         FillGpu fill = new FillGpu(gpu.context(), codegen.fillSource(step, corners, step, step, step, step), noiseData, permutations, corners.size(), 0);
         double fillCompileMs = (System.nanoTime() - fillStart) / 1.0e6;
         FillGpu.Job job = new FillGpu.Job();
         job.cells = new double[samplers * 289];
         cells.get(0, job.cells);
         job.chunkX = -4096;
         job.chunkZ = 8192;
         job.cellMinY = -16;
         job.cellCountY = cellCountY;
         job.cellWidth = 4;
         job.cellHeight = 8;
         job.seedLo = 123456789L;
         job.seedHi = -987654321L;
         job.veins = true;
         System.arraycopy(grid, 0, job.grid, 0, 6);
         System.arraycopy(lava, 0, job.lava, 0, 256);
         job.cellsUsed = 3 * 42 * 3;
         job.loc = loc;
         job.status = new int[job.cellsUsed * 3];
         for (int i = 0; i < job.cellsUsed; i++) {
            job.status[i * 3] = status[i * 2];
            job.status[i * 3 + 1] = status[i * 2 + 1];
            job.status[i * 3 + 2] = i % 7 == 0 ? 0 : i;
         }

         job.sea = 63;
         job.seaType = 8;
         byte[] vanilla = new byte[256 * height];
         byte[] c2me = new byte[256 * height];
         job.aquifer = 1;
         fill.fill(job, vanilla);
         long fillRun = System.nanoTime();
         job.aquifer = 2;
         fill.fill(job, c2me);
         double fillMs = (System.nanoTime() - fillRun) / 1.0e6;
         int differ = 0;
         int differC2me = 0;
         int flagged = 0;
         int flaggedC2me = 0;
         for (int i = 0; i < 256 * height; i++) {
            if ((vanilla[i] & 15) != codes.get(i)) {
               differ++;
            }

            if ((c2me[i] & 15) != codes.get(i)) {
               differC2me++;
            }

            flagged += (vanilla[i] & 16) != 0 ? 1 : 0;
            flaggedC2me += (c2me[i] & 16) != 0 ? 1 : 0;
         }

         // Column hoisting (the in-game fill's code): a codegen of its own must give the same codes byte for byte.
         DensityCodegen hoisted = new DensityCodegen();
         hoisted.hoistColumns(true);
         String hoistedStep = hoisted.function(root, DensityCodegen.Mode.BLOCK_STEP);
         List<String> hoistedCorners = new ArrayList<>();
         for (Object input : hoisted.interpolatorInputs()) {
            hoistedCorners.add(hoisted.function(input, DensityCodegen.Mode.CORNER));
         }

         FillGpu fillHoisted = new FillGpu(gpu.context(), hoisted.fillSource(hoistedStep, hoistedCorners, hoistedStep, hoistedStep, hoistedStep, hoistedStep),
            hoisted.noiseData(), hoisted.permutations(), hoistedCorners.size(), hoisted.columnFunctions().size());
         byte[] c2meHoisted = new byte[256 * height];
         fillHoisted.fill(job, c2meHoisted);
         long hoistRun = System.nanoTime();
         fillHoisted.fill(job, c2meHoisted);
         double hoistMs = (System.nanoTime() - hoistRun) / 1.0e6;
         System.out.printf(Locale.ROOT, "noise fill with %d subtrees once per column: %s against the plain fill, %,d blocks in %.2f ms%n",
            hoisted.columnFunctions().size(), java.util.Arrays.equals(c2me, c2meHoisted) ? "IDENTICAL" : "DIFFERENT", 256 * height, hoistMs);
         System.out.printf(Locale.ROOT,
            "noise fill: compiled in %.0f ms, %,d blocks in %.2f ms; vanilla aquifer: %s against densityStates, %,d flagged; C2ME's: %,d state codes differ (equal distances broken the other way), %,d flagged%n",
            fillCompileMs, 256 * height, fillMs, differ == 0 ? "IDENTICAL" : differ + " DIFFER", flagged, differC2me, flaggedC2me);
      }
   }
}
